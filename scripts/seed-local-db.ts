/**
 * Dumps the live content tables into supabase/seeds/10_content.sql, so
 * `npm run db:reset` gives the local stack the same content the real site
 * serves.
 *
 *   npm run db:seed        # refresh the dump
 *   npm run db:reset       # rebuild the local db, migrations + seeds
 *
 * Reads SEED_SOURCE_SUPABASE_URL / SEED_SOURCE_SUPABASE_ANON_KEY from
 * .env.local — the hosted project, not whatever VITE_SUPABASE_URL currently
 * points at, since during local development that is the local stack. Every
 * content table is publicly readable and the anon key ships in the browser
 * bundle anyway, so no service-role key is involved. Asset URLs are copied verbatim
 * and keep pointing at the hosted Storage buckets, which are public, so images
 * and patches load locally without downloading a thing. Files uploaded through
 * the local admin panel go to the local buckets instead.
 *
 * The generated file is gitignored: it is a snapshot, re-run it whenever the
 * live content moves on.
 */
import { createClient } from "@supabase/supabase-js";
import { mkdir, writeFile } from "node:fs/promises";
import path from "node:path";

const OUT_FILE = path.join(
  import.meta.dirname,
  "..",
  "supabase",
  "seeds",
  "10_content.sql",
);

try {
  process.loadEnvFile(".env.local");
} catch {
  // Fall back to whatever is already exported in the environment.
}

const supabaseUrl =
  process.env.SEED_SOURCE_SUPABASE_URL ?? process.env.VITE_SUPABASE_URL;
const anonKey =
  process.env.SEED_SOURCE_SUPABASE_ANON_KEY ??
  process.env.VITE_SUPABASE_ANON_KEY;

if (!supabaseUrl || !anonKey) {
  console.error(
    "Missing SEED_SOURCE_SUPABASE_URL / SEED_SOURCE_SUPABASE_ANON_KEY in .env.local.",
  );
  process.exit(1);
}

if (supabaseUrl.includes("127.0.0.1") || supabaseUrl.includes("localhost")) {
  console.error(
    `Refusing to dump ${supabaseUrl}: that is the local stack. Set ` +
      "SEED_SOURCE_SUPABASE_URL / SEED_SOURCE_SUPABASE_ANON_KEY in .env.local " +
      "to the hosted project's values (Supabase dashboard -> Project Settings " +
      "-> API).",
  );
  process.exit(1);
}

const supabase = createClient(supabaseUrl, anonKey);

type Row = Record<string, unknown>;

/** Renders a JS value as a Postgres literal. */
const literal = (value: unknown): string => {
  if (value === null || value === undefined) return "null";
  if (typeof value === "number") return String(value);
  if (typeof value === "boolean") return String(value);
  if (Array.isArray(value)) {
    return value.length === 0
      ? "'{}'::text[]"
      : `array[${value.map(literal).join(", ")}]::text[]`;
  }
  return `'${String(value).replaceAll("'", "''")}'`;
};

const insertStatement = (table: string, columns: string[], rows: Row[]) => {
  if (rows.length === 0) return `-- ${table}: no rows\n`;
  const values = rows
    .map((row) => `  (${columns.map((column) => literal(row[column])).join(", ")})`)
    .join(",\n");
  return `insert into public.${table} (${columns.join(", ")}) values\n${values};\n`;
};

const fetchAll = async (table: string, columns: string[], orderBy: string) => {
  const { data, error } = await supabase
    .from(table)
    .select(columns.join(", "))
    .order(orderBy);
  if (error) throw new Error(`Failed to read ${table}: ${error.message}`);
  return (data ?? []) as unknown as Row[];
};

// `content_images` / `content_downloads` ids are `generated always as
// identity`, so they are left out of the dump and regenerated on insert.
// Dumping them in id order keeps the relative order db.ts sorts on.
const tables = [
  { table: "games", columns: ["id", "name", "console", "sha1", "crc32"], orderBy: "id" },
  {
    table: "content_items",
    columns: [
      "id", "type", "game_ids", "name", "authors", "description", "date", "position",
    ],
    orderBy: "position",
  },
  {
    table: "content_images",
    columns: ["content_id", "url", "position"],
    orderBy: "id",
  },
  {
    table: "content_downloads",
    columns: ["content_id", "name", "path", "date"],
    orderBy: "id",
  },
  {
    table: "timeline_entries",
    columns: ["id", "date", "name", "description", "image"],
    orderBy: "date",
  },
];

const sections = await Promise.all(
  tables.map(async ({ table, columns, orderBy }) => {
    const rows = await fetchAll(table, columns, orderBy);
    console.log(`${table}: ${rows.length} rows`);
    return insertStatement(table, columns, rows);
  }),
);

const sql = `-- Generated by \`npm run db:seed\` from ${supabaseUrl} on ${new Date().toISOString()}.
-- Do not edit by hand; re-run the script instead.
--
-- Local seed data only. Asset URLs point at the hosted (public) Storage
-- buckets, so images and patches resolve without a local copy.

-- String literals are escaped by doubling quotes only, so backslashes must
-- stay literal.
set standard_conforming_strings = on;

delete from public.content_items;
delete from public.games;
delete from public.timeline_entries;

${sections.join("\n")}`;

await mkdir(path.dirname(OUT_FILE), { recursive: true });
await writeFile(OUT_FILE, sql);
console.log(`\nWrote ${path.relative(process.cwd(), OUT_FILE)}`);
